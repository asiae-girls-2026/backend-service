BEGIN;

CREATE TABLE IF NOT EXISTS public.med_dur_code_mapping (
    mapping_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    dur_code varchar(30) NOT NULL,
    mtral_code varchar(30) NOT NULL,

    match_method varchar(50) NOT NULL,
    review_status varchar(20) NOT NULL DEFAULT 'PENDING',

    evidence_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    review_note text,
    reviewed_at timestamptz,

    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_med_dur_code_mapping
        UNIQUE (dur_code, mtral_code),

    CONSTRAINT ck_med_dur_mapping_status
        CHECK (
            review_status IN (
                'PENDING',
                'APPROVED',
                'REJECTED'
            )
        )
);

CREATE INDEX IF NOT EXISTS
    idx_med_dur_mapping_mtral
ON public.med_dur_code_mapping (mtral_code);

CREATE INDEX IF NOT EXISTS
    idx_med_dur_mapping_review
ON public.med_dur_code_mapping (review_status);

COMMIT;
