-- CarePong medication phase 2 / B-contract schema migration
-- PostgreSQL. Run once after confirming an RDS snapshot and the target database.
-- This migration adds structures only; no existing rows are deleted or rewritten.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

-- Fail early if this is an unexpected database/schema.
DO $$
BEGIN
  IF to_regclass('public.users') IS NULL
    OR to_regclass('public.med_product') IS NULL
    OR to_regclass('public.hff_product') IS NULL
    OR to_regclass('public.user_medication') IS NULL THEN
    RAISE EXCEPTION 'Existing CarePong master tables are missing; abort';
  END IF;
  IF EXISTS (
    SELECT 1 FROM pg_tables
    WHERE schemaname='public'
      AND tablename IN (
      'canonical_ingredient','ingredient_alias','med_product_ingredient',
      'hff_product_ingredient','hff_ingredient_standard','med_safety_rule',
      'interaction_rule','mapping_candidate','mapping_audit','sync_run',
      'source_provenance','rule_release','medication_occurrence',
      'medication_intake_event','drug_class','drug_class_ingredient')
  ) THEN
    RAISE EXCEPTION 'At least one target table exists; do not run partial duplicate migration';
  END IF;
END $$;

CREATE TABLE public.canonical_ingredient (
 ingredient_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 canonical_name_ko varchar(300) NOT NULL,
 canonical_name_en varchar(300),
 normalized_key varchar(300) NOT NULL UNIQUE,
 domain_type varchar(10) NOT NULL,
 ingredient_type varchar(50),
 active boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.ingredient_alias (
 alias_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ingredient_id bigint NOT NULL REFERENCES public.canonical_ingredient(ingredient_id),
 alias_text varchar(300) NOT NULL,
 normalized_alias varchar(300) NOT NULL,
 source_dataset varchar(50),
 mapping_method varchar(20) NOT NULL,
 confidence numeric(5,4) CHECK (confidence BETWEEN 0 AND 1),
 status varchar(20) NOT NULL DEFAULT 'PENDING'
   CHECK (status IN ('PENDING','APPROVED','REJECTED'))
);
CREATE INDEX ingredient_alias_normalized_idx ON public.ingredient_alias(normalized_alias);

CREATE TABLE public.med_product_ingredient (
 med_product_ingredient_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 med_product_id bigint NOT NULL REFERENCES public.med_product(med_product_id),
 ingredient_id bigint REFERENCES public.canonical_ingredient(ingredient_id),
 source_ingredient_name varchar(300) NOT NULL,
 amount numeric(18,6),
 unit varchar(50),
 source_code varchar(100),
 mapping_status varchar(20) NOT NULL DEFAULT 'REVIEW',
 CONSTRAINT med_mapping_matched_has_id CHECK (mapping_status <> 'MATCHED' OR ingredient_id IS NOT NULL)
);
CREATE INDEX med_ingredient_product_idx ON public.med_product_ingredient(med_product_id);
CREATE INDEX med_ingredient_ingredient_idx ON public.med_product_ingredient(ingredient_id);

CREATE TABLE public.hff_product_ingredient (
 hff_product_ingredient_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 hff_product_id bigint NOT NULL REFERENCES public.hff_product(hff_product_id),
 ingredient_id bigint REFERENCES public.canonical_ingredient(ingredient_id),
 raw_ingredient_name varchar(500) NOT NULL,
 normalized_name varchar(300),
 mapping_method varchar(20),
 match_confidence numeric(5,4) CHECK (match_confidence BETWEEN 0 AND 1),
 mapping_status varchar(20) NOT NULL DEFAULT 'REVIEW',
 CONSTRAINT hff_mapping_matched_has_id CHECK (mapping_status <> 'MATCHED' OR ingredient_id IS NOT NULL)
);
CREATE INDEX hff_ingredient_product_idx ON public.hff_product_ingredient(hff_product_id);
CREATE INDEX hff_ingredient_ingredient_idx ON public.hff_product_ingredient(ingredient_id);

CREATE TABLE public.hff_ingredient_standard (
 standard_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ingredient_id bigint NOT NULL REFERENCES public.canonical_ingredient(ingredient_id),
 source_type varchar(10) NOT NULL,
 approval_no varchar(100),
 function_text text,
 daily_intake_min numeric(18,6),
 daily_intake_max numeric(18,6),
 unit varchar(50),
 caution_text text,
 source_record_id varchar(150),
 CONSTRAINT hff_standard_range CHECK (
 daily_intake_min IS NULL OR daily_intake_max IS NULL OR daily_intake_min <= daily_intake_max)
);

CREATE TABLE public.med_safety_rule (
 rule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rule_type varchar(50) NOT NULL,
 ingredient_id bigint REFERENCES public.canonical_ingredient(ingredient_id),
 paired_ingredient_id bigint REFERENCES public.canonical_ingredient(ingredient_id),
 target_group varchar(100),
 condition_value varchar(300),
 warning_text text NOT NULL,
 source_record_id varchar(150) NOT NULL,
 active boolean NOT NULL DEFAULT false
);
CREATE INDEX med_safety_ingredient_idx ON public.med_safety_rule(ingredient_id,paired_ingredient_id);

CREATE TABLE public.mapping_candidate (
 candidate_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entity_type varchar(30) NOT NULL,
 raw_value varchar(500) NOT NULL,
 candidate_entity_id bigint,
 match_method varchar(20) NOT NULL,
 confidence numeric(5,4) CHECK (confidence BETWEEN 0 AND 1),
 source_dataset varchar(50) NOT NULL,
 status varchar(20) NOT NULL DEFAULT 'PENDING'
   CHECK (status IN ('PENDING','APPROVED','REJECTED')),
 created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.mapping_audit (
 mapping_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entity_type varchar(30) NOT NULL,
 raw_value varchar(500) NOT NULL,
 canonical_entity_id bigint NOT NULL,
 method varchar(20) NOT NULL,
 confidence numeric(5,4) CHECK (confidence BETWEEN 0 AND 1),
 approved_by varchar(100),
 approved_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.sync_run (
 sync_run_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dataset_code varchar(100) NOT NULL,
 started_at timestamptz NOT NULL,
 finished_at timestamptz,
 status varchar(20) NOT NULL,
 fetched_count integer NOT NULL DEFAULT 0,
 inserted_count integer NOT NULL DEFAULT 0,
 updated_count integer NOT NULL DEFAULT 0,
 unchanged_count integer NOT NULL DEFAULT 0,
 failed_count integer NOT NULL DEFAULT 0,
 error_message text
);
CREATE INDEX sync_run_dataset_started_idx ON public.sync_run(dataset_code,started_at DESC);

CREATE TABLE public.source_provenance (
 provenance_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entity_type varchar(20) NOT NULL,
 entity_id bigint NOT NULL,
 dataset_code varchar(100) NOT NULL,
 source_record_id varchar(150) NOT NULL,
 source_updated_at timestamptz,
 fetched_at timestamptz NOT NULL,
 raw_hash varchar(64),
 sync_run_id bigint REFERENCES public.sync_run(sync_run_id)
);
CREATE INDEX provenance_entity_idx ON public.source_provenance(entity_type,entity_id);

CREATE TABLE public.rule_release (
 rule_release_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 release_code varchar(80) NOT NULL UNIQUE,
 released_at timestamptz,
 status varchar(20) NOT NULL DEFAULT 'DRAFT'
   CHECK (status IN ('DRAFT','ACTIVE','RETIRED')),
