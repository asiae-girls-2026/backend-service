-- DB-level defense: active rules require approved review and ACTIVE release.
CREATE FUNCTION public.carepong_validate_interaction_rule_activation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.active AND NOT EXISTS (
   SELECT 1 FROM public.rule_release r
   WHERE r.rule_release_id=NEW.rule_release_id AND r.status='ACTIVE'
 ) THEN
   RAISE EXCEPTION 'Cannot activate interaction rule without ACTIVE rule release';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_interaction_rule_activation
BEFORE INSERT OR UPDATE OF active,review_status,rule_release_id
ON public.interaction_rule
FOR EACH ROW EXECUTE FUNCTION public.carepong_validate_interaction_rule_activation();

-- Cross-record user ownership checks (FKs alone cannot enforce this).
CREATE FUNCTION public.carepong_validate_medication_ownership()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS (
  SELECT 1 FROM public.user_medication m
  WHERE m.user_medication_id=NEW.user_medication_id AND m.user_id=NEW.user_id
 ) THEN
  RAISE EXCEPTION 'User medication ownership mismatch';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_occurrence_medication_ownership
BEFORE INSERT OR UPDATE OF user_medication_id,user_id
ON public.medication_occurrence
FOR EACH ROW EXECUTE FUNCTION public.carepong_validate_medication_ownership();
CREATE TRIGGER trg_intake_medication_ownership
BEFORE INSERT OR UPDATE OF user_medication_id,user_id
ON public.medication_intake_event
FOR EACH ROW EXECUTE FUNCTION public.carepong_validate_medication_ownership();
