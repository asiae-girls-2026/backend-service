);
-- Only one active release, enforcing explicit cutover.
CREATE UNIQUE INDEX rule_release_one_active ON public.rule_release((1)) WHERE status='ACTIVE';

CREATE TABLE public.drug_class (
 drug_class_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 class_code varchar(100),
 class_name varchar(300) NOT NULL,
 source_dataset varchar(100) NOT NULL,
 review_status varchar(20) NOT NULL DEFAULT 'PENDING'
   CHECK (review_status IN ('PENDING','APPROVED','REJECTED'))
);
CREATE TABLE public.drug_class_ingredient (
 drug_class_id bigint NOT NULL REFERENCES public.drug_class(drug_class_id),
 ingredient_id bigint NOT NULL REFERENCES public.canonical_ingredient(ingredient_id),
 review_status varchar(20) NOT NULL DEFAULT 'PENDING'
   CHECK (review_status IN ('PENDING','APPROVED','REJECTED')),
 PRIMARY KEY (drug_class_id,ingredient_id)
);

CREATE TABLE public.interaction_rule (
 interaction_rule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subject_type varchar(20) NOT NULL CHECK (subject_type IN ('PRODUCT','INGREDIENT','DRUG_CLASS')),
 subject_id bigint NOT NULL,
 object_type varchar(20) NOT NULL CHECK (object_type IN ('PRODUCT','INGREDIENT','DRUG_CLASS')),
 object_id bigint NOT NULL,
 interaction_type varchar(20) NOT NULL,
 severity varchar(30),
 action_type varchar(30) NOT NULL,
 evidence_text text NOT NULL,
 source_dataset varchar(50) NOT NULL,
 source_record_id varchar(150) NOT NULL,
 review_status varchar(20) NOT NULL DEFAULT 'PENDING'
   CHECK (review_status IN ('PENDING','APPROVED','REJECTED')),
 active boolean NOT NULL DEFAULT false,
 target_text text,
 rule_release_id bigint REFERENCES public.rule_release(rule_release_id),
 CONSTRAINT interaction_active_requires_review CHECK (
   NOT active OR (review_status='APPROVED' AND rule_release_id IS NOT NULL))
);
CREATE INDEX interaction_subject_idx ON public.interaction_rule(subject_type,subject_id);
CREATE INDEX interaction_object_idx ON public.interaction_rule(object_type,object_id);
CREATE INDEX interaction_release_idx ON public.interaction_rule(rule_release_id);

